"""
    write_params_mod(mod_dir, p) -> String

Generate `mod_dir/params_jl.mod` containing explicit Dynare parameter
assignments for all scalars, sectoral vectors and the IO matrix.

Arguments:
  mod_dir  : directory that contains NK_SOE_lev_gap2.mod
  p        : NamedTuple or Dict with all computed steady-state values

The returned string is the path to the written file.
"""
function write_params_mod(mod_dir::String, p::NamedTuple)
    path = joinpath(mod_dir, "params_jl.mod")
    nsec = p.nsec

    # MODEL-DEFINING FIELDS MUST BE PRESENT (2026-08-20).
    #
    # These used to fall back to a default via hasproperty(), which meant a
    # caller that had not been updated silently built a DIFFERENT MODEL and said
    # nothing: subsMC -> 1.0 removed the LPR markup subsidy, modGi -> 0 removed
    # government consumption entirely, modtfpY -> 1 put mining's TFP back into
    # its production function. oil_shock_analysis.jl was in exactly that state.
    # Fail loudly instead — a missing field is always a caller that needs
    # updating, never something to paper over.
    for fld in (:subsMC_val, :modGi, :modtfpY, :gshare_target,
                :modalphaK, :modKbar, :modchiI, :modRKss, :nuK_val, :PIinv_ss_val)
        hasproperty(p, fld) || error("""
            write_params_mod: params NamedTuple is missing `$(fld)`.
            This field defines the model, so it cannot be defaulted. The caller
            predates a model change — add it there. Callers that build params:
            main_SOE_gap.jl and oil_shock_analysis.jl.
            """)
    end

    open(path, "w") do io
        println(io, "// -------------------------------------------------------")
        println(io, "// params_jl.mod  —  auto-generated by main_SOE_gap.jl")
        println(io, "// Do NOT edit manually; re-run main_SOE_gap.jl to refresh.")
        println(io, "// -------------------------------------------------------")
        println(io)

        # ---- Scalar structural parameters -------------------------------- #
        _wp(io, "sigma_i",      p.sigma_i_val)
        _wp(io, "sigma_L_agg",  p.sigma_L_agg_val)
        _wp(io, "ilabcosts",    p.ilabcosts_val)
        _wp(io, "gamma",        p.gamma_val)
        _wp(io, "psi",          get(p, :psi_val, 1.5))
        # GHH disutility scale chi0 = chi_weight * C_ss^gamma (holds SS at KPR
        # values). Falls back to C_ss^gamma (chi_weight = 1) if not supplied.
        _wp(io, "chi0",         get(p, :chi0_val, p.C_ss^p.gamma_val))
        _wp(io, "beta",         p.beta_val)
        _wp(io, "phi",          p.phi_val)
        _wp(io, "epsilon",      10.0)
        _wp(io, "rho",          p.rho_val)
        _wp(io, "rho_om1",      p.rho_om1_val)
        # rho_tfp1 accepts a scalar (common TFP persistence) or an nsec-vector
        # (sector-specific, e.g. transitory agriculture shock with half-life of
        # half a quarter → ρ = 0.25).  The lev mod uses the sectoral parameters
        # rho_tfp1_<i> (written in the loop below); the scalar alias is kept for
        # the SMM mod, whose equations use the common rho_tfp1.  When a vector
        # is passed, the alias takes the LAST entry (an unshocked sector =
        # common persistence) — it is unused by the lev mod in that case.
        _rho_tfp1_vec = p.rho_tfp1_val isa AbstractVector ?
            collect(Float64, p.rho_tfp1_val) : fill(Float64(p.rho_tfp1_val), p.nsec)
        _wp(io, "rho_tfp1",     _rho_tfp1_vec[end])
        _wp(io, "rho_tfp2",     p.rho_tfp2_val)
        _wp(io, "rhoi",         0.5)          # rhoi = 0.5 + 0*rhoi_val
        _wp(io, "rhoirule",     p.rhoirule_val)
        _wp(io, "ombar",        p.ombar_val)
        _wp(io, "phi_b",       p.phi_b_val)
        _wp(io, "bbar",         p.bbar_val)
        _wp(io, "epsilonX",     p.epsilonX_val)
        _wp(io, "omegaX",       p.omegaX_val)
        _wp(io, "ystar_ss",     p.ystar_ss_val)
        _wp(io, "etastar",      p.etastar_val)
        _wp(io, "epsilonV",     p.epsilonV_val)
        _wp(io, "kappaV",       p.kappaV_val)
        _wp(io, "sigmaH",       p.sigmaH_val)
        _wp(io, "Pistar_ss",    p.Pistar_ss_val)
        _wp(io, "PVstar_ss",    p.PVstar_ss_val)
        _wp(io, "rho_pvstar",   p.rho_pvstar_val)
        _wp(io, "sigma_pvstar", p.sigma_pvstar_val)
        _wp(io, "rho_zeta",       p.rho_zeta_val)
        _wp(io, "sigma_zeta",     p.sigma_zeta_val)
        _wp(io, "Rworld_ss",    p.Rworld_ss_val)
        # Sticky wages (Rotemberg wage PC). Defaults apply unless the driver
        # passes epsw_val / kappaw_val in the params NamedTuple.
        # kappaw default 115 ≈ Calvo wage duration of 4 quarters:
        # slope = (1-θw)(1-βθw)/θw = 0.0868 with θw=0.75, β=0.986 → κw = εw/slope.
        # kappaw = 0 → flexible wages (nests the pre-2026-07 model exactly).
        _wp(io, "epsw",   get(p, :epsw_val,   10.0))
        _wp(io, "kappaw", get(p, :kappaw_val, 115.0))
        # Oil sector scalar parameters
        _wp(io, "epsilonV_oil",    p.epsilonV_oil_val)
        _wp(io, "rho_postar",      p.rho_postar_val)
        _wp(io, "sigma_postar",    p.sigma_postar_val)
        _wp(io, "POstar_ss",       p.POstar_ss_val)
        _wp(io, "shock_eps_postar",p.shock_eps_postar_val)
        _wp(io, "rho_pc",         p.rho_pc_val)
        _wp(io, "sigma_pc",       p.sigma_pc_val)
        _wp(io, "Pcstar_ss",      p.Pcstar_ss_val)
        _wp(io, "shock_eps_pc",   p.shock_eps_pc_val)
        _wp(io, "Y2_ss",          p.Y2_ss_val)
        _wp(io, "X_cu_ss",        p.X_cu_ss_val)
        _wp(io, "phi_cu",         p.phi_cu_val)
        # LPR semi-fixed capital: nuK = 1/phi, the capital supply elasticity.
        _wp(io, "nuK",            p.nuK_val)
        _wp(io, "PIinv_ss",       p.PIinv_ss_val)
        # G/GDP target, carried so the estimation can re-solve the same SS.
        _wp(io, "gshare_target",  p.gshare_target)
        # LPR markup subsidy: (1-tau) factor on MC in the pricing condition.
        # 1.0 = no subsidy (markup eps/(eps-1)); (eps-1)/eps = LPR (markup 1).
        _wp(io, "subsMC",         p.subsMC_val)
        _wp(io, "Pi_cu_ss",       p.Pi_cu_ss_val)
        _wp(io, "PH2_ss",         p.PH2_ss_val)
        println(io)

        # ---- Steady-state scalars ---------------------------------------- #
        # pi_ss = 1 (zero net domestic inflation in SS)
        # r_ss = Pistar_ss / beta (from household Euler equation)
        _wp(io, "pi_ss",   1.0)
        _wp(io, "r_ss",    p.Pistar_ss_val / p.beta_val)
        _wp(io, "w_ss",    p.w_ss)
        _wp(io, "C_ss",    p.C_ss)
        _wp(io, "GDP_ss",  p.GDP_ss)
