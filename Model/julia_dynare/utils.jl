"""
    safe_spearman(x, y) -> Float64

Spearman rank correlation. Returns 0.0 when `x` is nearly uniform (model std
devs identical across sectors), matching the smm_model_moments.m behaviour.
"""
function safe_spearman(x::AbstractVector{<:Real}, y::AbstractVector{<:Real})
    std(x) < 1e-12 * (abs(mean(x)) + 1e-12) && return 0.0
    return corspearman(x, y)
end


# =========================================================================== #
#  Discrete Lyapunov equation                                                  #
# =========================================================================== #

"""
    local_dlyap(A, Q) -> P

Solve  P = A P Aᵀ + Q  by the matrix-doubling algorithm.
Equivalent to MATLAB's dlyap(A', Q).
"""
function local_dlyap(A::AbstractMatrix{<:Real}, Q::AbstractMatrix{<:Real};
                     maxiter::Int=500, tol::Real=1e-14)
    P  = copy(Q)
    Ai = copy(A)
    for _ in 1:maxiter
        P_new = Ai * P * Ai' + P
        err   = norm(P_new - P, Inf) / (norm(P, Inf) + 1e-14)
        P     = (P_new + P_new') / 2
        Ai    = Ai * Ai
        err < tol && break
    end
    return (P + P') / 2
end


