# ---- Weighting matrix ------------------------------------------------------ #
# Sectoral value-added shares, % of total VA. Fixed, for ECONOMIC-SIZE moment
# weighting. Order = the 12 model sectors.
#
# SOURCE (2026-08-19): Chilean IO tables 2021, Data/2021_Cuadros_12x12.xlsx,
# Cuadro 23 "Valor agregado" — the same table the calibration is built from.
#
# WAS: [5.07, 12.63, 15.87, 2.90, 3.14, 3.34, 10.93, 6.71, 2.13, 26.03, 11.08,
# 0.17] — hardcoded from an OLD MODEL RUN, not from data, and that run used the
# pre-2026-08-19 cost-base alpha convention, so it was stale twice over. It
# systematically downweighted exactly the sectors the model fits worst:
#
#   sector                  old      data     ratio
#   Administracion publica  0.17%    5.08%    x29.9
#   Serv. inmobiliarios     2.13%    8.55%    x4.0
#   Comercio                3.34%   12.66%    x3.8
#   Construccion            3.14%    6.45%    x2.1
#   Serv. empresariales    26.03%    9.75%    x0.37
#
# Effect on the criterion is small (total objective 15.09 -> 15.13 at the July
# theta) because the sectoral blocks are only ~21% of it — but it changes WHICH
# sectors the optimiser chases, and a model-derived weight matrix is not
# defensible in a replication package.
const SECTOR_VA_SHARE = let s = [3.92, 15.78, 9.54, 2.79, 6.45, 12.66,
                                 8.31,  3.91, 8.55, 9.75, 13.27, 5.08]
    s ./ sum(s)
end

"""
Sectors whose national-accounts output is NOT a market outcome, and whose
volatility and price-quantity correlation are therefore accounting conventions:

  9  Real Estate          — dominated by imputed rent on owner-occupied housing
  12 Public Administration — output measured by inputs (compensation of employees)

See the NON-MARKET SECTORS block at the end of `build_weighting_matrix` for what
this does and why. Referenced by the paper's data section.
"""
const NONMARKET_SECTORS = [9, 12]

function build_weighting_matrix(dm::Vector{<:Real})
    w = ones(N_MOMENTS)
    # Sectoral volatility moments 1:36 = output(1:12), price(13:24), labor(25:36).
    # Weight each by the sector's VALUE-ADDED SHARE (economic size), NOT 1/d².
    # WHY: 1/d^2 pathologically over-weighted the SMALLEST-volatility sector —
    # Public Admin (data std 0.011) received weight ~7650, about 1200x
    # Agriculture, and its std(Y) miss alone was 40% of the objective.
    # (The original note here justified this with "0.17% of VA", which was the
    # MODEL's public-admin share under the old calibration, not the data's —
    # Cuadro 23 puts it at 5.08%. The 1/d^2 argument stands on its own.)
    # Size-weighting makes the objective track economic relevance; cross-sector
    # ORDERING stays disciplined by the rank-correlation moments (44-46).
    # SECT_BLOCK_W = total weight per 12-sector block (tunable).
    SECT_BLOCK_W = 1000.0
    for k in 1:36
        sec = ((k - 1) % 12) + 1
        w[k] = SECT_BLOCK_W * SECTOR_VA_SHARE[sec]
    end
    # 25-36, the twelve std(L_i) — UNTARGETED as of 2026-08-21, replaced by the
    # two goods/services aggregates at 79-80.
    #
    # FGI (2023) is the only paper in this literature that targets sectoral
    # employment at all, and they target TWO cross-sectional dispersion
    # statistics — one for goods, one for services — not twelve individual
    # sector volatilities. Twelve separate targets put a great deal of weight on
    # the least reliable series in the set: AFC/Seguro de Cesantia coverage
    # phases in through the early sample at very different rates by sector, and
    # the Ley de Proteccion al Empleo distorts 2020-21 (already excluded).
    # Aggregating to goods and services averages most of that away.
    #
    # Still computed and printed sector by sector, as untargeted diagnostics.
    let wl = parse(Float64, get(ENV, "SMM_W_STDL_SECTORAL", "0.0"))
        for k in 25:36
            w[k] = wl * SECT_BLOCK_W * SECTOR_VA_SHARE[((k - 1) % 12) + 1]
        end
    end
    # Aggregate stds (GDP, pi, TB, Q): keep inverse-squared-data weighting.
    for k in [37, 38, 40, 41]
        d = abs(dm[k]); w[k] = d > 1e-4 ? 1.0/d^2 : 1.0/0.01^2
    end
    # 39 = corr(GDP,pi). The old note here read "structurally hard for supply-
    # shock model" and cut the weight to 0.20. That has the economics backwards.
    # A supply shock raises output and lowers prices, so a SUPPLY-driven economy
    # is exactly what produces corr(GDP,pi) < 0; it is a DEMAND-driven model
    # that struggles with the data's negative sign. The model's problem was
    # never the sign — it delivered -0.162 against -0.421 — it was that the
    # correlation was too WEAK, which is the same message as lambda_om = 3.14:
    # too much demand in the shock mix.
    #
    # Most of the residual gap was the pandemic. On the data, HP-filtered:
    #     corr(GDP,pi)  full sample      -0.392
    #                   excl. 2020Q1-21Q2 -0.213
    # against a model -0.162. With COVID excluded (compute_data_moments.jl)
    # this moment is very nearly matched already.
    #
    # So it is restored to full weight, and treated as what it is: the AGGREGATE
    # counterpart of the corr(Y_i,PH_i) block, carrying information about the
    # same supply/demand mix. Weight 3.0 to match that block — bounded in
    # [-1,1], so a fixed weight, per the convention above.
    w[39] = parse(Float64, get(ENV, "SMM_W_CORR_GDPPI", "3.0"))
    # 42 = autocorr(Q). The old note said this identifies rho_pvstar, but
    # rho_pvstar has been PINNED at its measured ToT AR(1) since the shock
    # redesign, so this moment was identifying nothing. It is now the main
    # source of information on rho_zeta — see the note at sigma_zeta's bound in
    # the LB/UB block — and the model misses it badly (0.426 vs 0.716).
    w[42]  = 2.0
    # 44-46 RANK CORRELATIONS — UNTARGETED as of 2026-08-21, still computed and
    # printed. This is a considered removal, not "the model could not match them".
    #
    # A literature pass over Ferrante-Graves-Iacoviello (2023), Atalay (2017),
    # Foerster-Sarte-Watson (2011), Rubbo (2023), Luttini-Pasten-Rubbo (2024),
    # Baqaee-Farhi (2022), Imbs-Jondeau-Pelgrin (2011), Garcia-Cicco-Pancrazi-
    # Uribe (2010), Schmitt-Grohe-Uribe (2018) and XMAS found the words
    # "Spearman", "rank correlation" and "Kendall" ZERO times. Nobody targets a
    # rank statistic of a second moment. The closest relative is FGI's
    # rho(y_data, y_model), which is PEARSON on the level of sectoral changes —
    # "is the right sector in the right place" — not Spearman on the ORDERING of
    # volatilities.
    #
    # They are also badly behaved as an objective: a Spearman correlation is a
    # step function of theta, so it is locally flat and globally cliffed. That is
    # visible in the CMA-ES traces, which sit on identical objective values for
    # hundreds of evaluations.
    #
    # They are replaced by moment 78, rbar, which measures the same economics
    # (cross-sectoral comovement) with the statistic this literature actually
    # uses, and is smooth in theta.
    #
    # Reporting them as untargeted also fills a real gap: FGI, Baqaee-Farhi,
    # GCPU, SGU and Rubbo all reserve something for out-of-sample validation and
    # this objective reserved nothing. SMM_W_RANK restores a positive weight.
    let wrank = parse(Float64, get(ENV, "SMM_W_RANK", "0.0"))
        w[44] = wrank; w[45] = wrank; w[46] = wrank
    end
    # 46 = LABOUR rank correlation. KEPT TARGETED at the same weight (2026-08-21).
    #
    # This moment was briefly set to zero earlier the same day on the grounds
    # that it was unattainable — spearman(std L_i, std Y_i) = -0.231 in the data
    # against +0.336 in the model, a sign the model cannot flip. That argument
    # was WRONG, and the record is worth keeping because the failure mode is
    # easy to repeat: the -0.231 was not a fact about Chile, it was a SAMPLE
    # MISMATCH. std_L and std_PH were being computed on 2006Q1-2023Q4 while
    # std_Y and corr_YPH used 2013Q1-2023Q4 (the SA output vintage starts in
    # 2013). Two cross-sections measured over different decades. Align them and
    #     spearman(std L_i, std Y_i) = +0.000
    # The -0.231 came almost entirely from AFC coverage phase-in over 2006-2012
    # in Mining, Finance and Public Admin. Fixed in compute_data_moments.jl §4b.
    #
    # +0.000 versus a model +0.336 is a real gap but an ordinary one: no sign
    # impossibility, so it stays in the objective and the model has to answer
    # for it. Note the data source is sound — AFC / Seguro de Cesantía
    # administrative records, which is the intended source; a Poisson/binomial
    # cell-size noise floor is only ~15% of the measured std and correlates just
    # +0.14 with std(L_i), so the cross-section is not driven by sampling noise.
    #
    # OPEN ISSUE for the 2020-21 window, worth a robustness check rather than a
    # weight change: under the Ley de Protección al Empleo (21.227, April 2020)
    # suspended workers stayed on the AFC register, so AFC headcount barely fell
    # in exactly the sectors whose output collapsed (Personal services -20.6%
    # output vs -4.5% employment; Trade/Hotels -24.6% vs -10.5%). Excluding
    # 2020Q1-2021Q2 moves the aligned rank correlation from +0.000 to -0.182.
    #
    # SMM_W_LABOR_RANK still overrides moment 46 alone, on top of SMM_W_RANK.
    haskey(ENV, "SMM_W_LABOR_RANK") && (w[46] = parse(Float64, ENV["SMM_W_LABOR_RANK"]))
    # corr(Y_i,PH_i): FIXED weight (2026-07-09). Old proportional 1.5/d²
    # exploded for near-zero data correlations (sector 10: w≈30,800) and made
    # this block 99.5% of the objective. Correlations are bounded [-1,1] →
    # fixed weight, 1.5× the rank weight to keep identification emphasis.
    for k in 47:58
        w[k] = 3.0
    end
    w[59] = 2.0; w[60] = 2.0   # corr(N,GDP), corr(N,GDP/N)
    # std(omG), the goods expenditure share (2026-08-19). Inverse-squared-data
    # weighting, as for the other aggregate std moments (37,38,40,41). This is
    # the moment that identifies sigma_omg — under Cobb-Douglas omega_t IS the
    # goods expenditure share (FGI 2023 eq. 12), so the mapping is direct.
    let d = abs(dm[61]); w[61] = d > 1e-4 ? 1.0/d^2 : 1.0/0.01^2 end
    # 62 std(pi_g - pi_s): inverse-squared-data, consistent with the other
    # aggregate std moments (37,38,40,41). 63 corr(pi_g - pi_s, om_g): fixed
    # weight, as for every other correlation — bounded in [-1,1], so a
    # proportional weight would explode near zero (that pathology is what the
    # corr(Y_i,PH_i) note above records). 3.0 matches the corr(Y_i,PH_i) block,
    # i.e. the same emphasis as the other identification-carrying correlations.
    let d = abs(dm[62]); w[62] = d > 1e-4 ? 1.0/d^2 : 1.0/0.01^2 end
    w[63] = 3.0
    # 64-77 PERSISTENCE (2026-08-21). Autocorrelations are bounded in [-1,1],
    # so fixed weights, per the convention above — a proportional weight would
    # explode for a sector whose data autocorrelation is near zero.
    #
    # 64-65 aggregate: 2.0, matching autocorr(Q) (w[42]). These are what
    # discipline rho_A and stop it running to its bound.
    # 66-77 sectoral: 1.0 each. Deliberately modest. Twelve new moments at
    # correlation-scale weights would swamp a total objective of order 10; at
    # 1.0 with typical misses of 0.2-0.4 the block carries ~1, comparable to
    # the std(PH_i) block. The point of these twelve is to make the COMMON
    # rho_A restriction testable, not to dominate the fit.
    w[64] = parse(Float64, get(ENV, "SMM_W_AC_AGG",  "2.0"))
    w[65] = w[64]
    let wac = parse(Float64, get(ENV, "SMM_W_AC_SEC", "1.0"))
        for k in 66:77
            w[k] = wac
        end
    end
    # ---- 78-84: the literature-standard replacements (2026-08-21) --------- #
    # 78 rbar — a correlation, bounded, so a fixed weight, at the same 3.0 as the
    #    other identification-carrying correlations. It replaces THREE rank
    #    moments that between them carried 6.0, so the block weight falls.
    w[78] = parse(Float64, get(ENV, "SMM_W_RBAR", "3.0"))
    # 79-80 goods/services average sectoral employment volatility. Inverse-
    #    squared-data, as for every other std moment. Between them these replace
    #    the twelve std(L_i).
    for k in 79:80
        d = abs(dm[k]); w[k] = d > 1e-4 ? 1.0/d^2 : 1.0/0.01^2
    end
    # 81-84 the SOE great ratios. std(C)/std(GDP) and std(I)/std(GDP) are RATIOS
    #    of order 1, so inverse-squared-data gives them a sensible scale;
    #    corr(C,GDP) and corr(I,GDP) are correlations, so fixed weight.
    #    GCPU (2010) Table 4 and XMAS Table 5 both report exactly this block.
    for k in 81:82
        d = abs(dm[k]); w[k] = d > 1e-3 ? 1.0/d^2 : 1.0
    end
    w[83] = 3.0; w[84] = 3.0

    # ---- NON-MARKET SECTORS (2026-08-24) ----------------------------------- #
    #
    # Real Estate (9) and Public Administration (12) are not market outcomes in
    # the national accounts, so their output, deflator, and the correlation
    # between them are accounting conventions rather than economic behaviour:
    #
    #   * Real Estate output is dominated by IMPUTED RENT on owner-occupied
    #     housing. It is constructed from the housing stock and a rental
    #     imputation, not from transactions, so it barely moves at business-cycle
    #     frequency and it has no market price to correlate with quantity.
    #   * Public Administration output is measured by INPUTS (compensation of
    #     employees), the standard convention for non-market government services.
    #     Its "price" is a deflator built from wages, so corr(Y,PH) is a
    #     restatement of the wage-employment split, not a supply/demand mix.
    #
    # The data say exactly this. These two are the LEAST volatile sectors in the
    # panel by a wide margin — std(Y) = 0.0081 and 0.0082 against 0.017-0.054 for
    # the other ten. That is a measurement artefact of smoothing-by-construction.
    #
    # It was not harmless. At the warm-start optimum of 2026-08-24, corr(Y_9,PH_9)
    # ALONE was 16.7% of the objective (data -0.400, model +0.289 — the model
    # cannot even get the sign, and should not be asked to), and the block
    # corr(Y_i,PH_i) was 51% of the total. The estimator was spending half its
    # effort on twelve moments of which the single largest is an imputation.
    #
    # This is why the literature works with market output: Foerster, Sarte &
    # Watson (2011 JPE) use industrial production and Atalay (2017) manufacturing.
    #
    # Weight 0.0 = computed and PRINTED as an untargeted diagnostic, never scored
    # — the same treatment already given to the twelve std(L_i) at 25-36. Set
    # SMM_W_NONMARKET to a fraction (e.g. 0.25) to downweight instead of drop.
    #
    # NOT changed here, and worth deciding separately: rbar (78) is still the
    # average over all 66 sector pairs, including the 21 pairs involving 9 or 12.
    # Consistency argues for recomputing it over the ten market sectors, but that
    # changes the DATA target too, so it needs a compute_data_moments.jl re-run.
    #
    # JUDGEMENT CALL LEFT OPEN: Personal Services (11) is the second-largest
    # contributor (10.5%) and in the Chilean CCNN it bundles education and health,
    # much of which is public and also input-measured. It is a MIXED sector, so it
    # is left targeted here. If it is added later, say so in the paper.
    let wnm = parse(Float64, get(ENV, "SMM_W_NONMARKET", "0.0"))
        for s in NONMARKET_SECTORS
            w[s]      *= wnm      # std(Y_i)
            w[12 + s] *= wnm      # std(PH_i)
            w[46 + s] *= wnm      # corr(Y_i,PH_i)
        end
    end

    return Diagonal(w) |> Matrix
end

# ---- Report printers ------------------------------------------------------- #
function print_param_table(θ::AbstractVector; io=stdout)
    @printf(io, "\n  %-3s %-16s %12s %10s %10s  %s\n",
            "#", "Parameter", "Value", "LB", "UB", "Bound?")
    println(io, "  ", repeat("-", 66))
    for k in 1:N_THETA
        span_k = UB[k] - LB[k]
        flag = θ[k] <= LB[k] + 0.02*span_k ? "<< at LB" :
               θ[k] >= UB[k] - 0.02*span_k ? ">> at UB" : ""
        @printf(io, "  %-3d %-16s %12.4f %10.3f %10.3f  %s\n",
                k, PARAM_LABELS[k], θ[k], LB[k], UB[k], flag)
    end
    println(io, "  ", repeat("-", 66))
    println(io, "  'at LB/UB' = within 2% of a bound: not identified there, or bound binds.")
end

function print_fit_table(dm::AbstractVector, mm::AbstractVector, W::AbstractMatrix; io=stdout)
    ψ  = dm .- mm
    wd = [W[i,i]*ψ[i]^2 for i in 1:N_MOMENTS]
    tot = sum(wd)
    @printf(io, "\n  %-34s %9s %9s %9s %10s %6s\n",
            "Moment", "Data", "Model", "Diff", "W*Diff2", "%obj")
    println(io, "  ", repeat("-", 84))
    for (rng, lbl) in MOMENT_BLOCKS
        bsum = sum(wd[rng])
        @printf(io, "  -- %-48s block %8.3f  %5.1f%% --\n", lbl, bsum, 100bsum/tot)
        for i in rng
            @printf(io, "  %-34s %9.5f %9.5f %+9.5f %10.4f %5.1f%%\n",
                    MOMENT_NAMES[i], dm[i], mm[i], ψ[i], wd[i], 100wd[i]/tot)
        end
    end
    println(io, "  ", repeat("-", 84))
    @printf(io, "  %-34s %29s %10.4f %6s\n", "TOTAL OBJECTIVE", "", tot, "100%")
end

